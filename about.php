          <h1 id="about-heading" class="section-title">About John Colins</h1>
         <p class="muted">John Colins (London, UK) is a textile artist and painter represented by CIRCLE Contemporary Gallery. Working from his studio in Dagenham, Adam’s practice is rooted in the materials, histories and atmosphere of his surrounding landscape.</p>
          <p class="muted">Meticulously crafted through layers of hand-dyed fabric and paint, John’s works come together over many months using both hand and machine stitching. These deeply textured compositions draw on the visual richness of algae, lichen, rust and weathered surfaces.</p>
        <p class="muted">Guided by a deep connection to genius loci, or the spirit of a place, John creates work that transcends visual depiction, offering instead a sensorial and emotional response to land and memory. His connection to the land is ancestral and lived—his great-grandfather’s relationship to the family farm infuses his work with a sense of belonging and reverence.</p>
          <p class="muted">His surroundings—ancient stone circles, unspoiled moorland and the quiet, expansive terrain of London—form both the backdrop and subject of his practice. These sites offer not only visual inspiration but also a quietude that is embedded into the very fabric of his work.</p>
